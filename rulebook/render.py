"""
render.py

Generates rulebook/RULEBOOK.md from rulebook/rules.json. RULEBOOK.md is never
hand-edited: change rules.json (via build_rules.py) and re-run this script.
One table per section, for review by a speaker / Prof. Mbogho.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
TRAIN = Path.home() / "languagemodels" / "rulebook_data" / "train.jsonl"
REVIEW = Path.home() / "languagemodels" / "rulebook_data" / "RULEBOOK_review.md"
SECTIONS = {1: "Noun classes and concord", 2: "Verb template", 3: "Tense / aspect / mood (Swahili -> Kidaw'ida)",
            4: "Negation", 5: "Extensions", 6: "Final vowel / perfective / -ghe", 7: "Copula and locatives",
            8: "Known gaps (flag only)"}
SRC = {"speaker_verified": "speaker", "corpus_attested": "corpus", "grammar_notes": "notes",
       "mined_alignment": "mined"}


def cell(x) -> str:
    if isinstance(x, dict):
        x = "; ".join(f"{k}: {cell(v)}" for k, v in x.items())
    elif isinstance(x, list):
        x = ", ".join(cell(v) for v in x)
    return str(x).replace("|", "/").replace("\n", " ")


def form_text(r: dict) -> str:
    t = dict(r["then"])
    bf = r["evidence"].get("by_form")
    if bf:
        weak = [f for f, v in bf.items() if not v["attested"]]
        if weak:
            t["unattested forms"] = weak
    return cell(t)


def example(r: dict, text: dict | None) -> str:
    if r["examples"]:
        e = r["examples"][0]
        if text and e["pair_id"] in text:
            sw, dav = text[e["pair_id"]]
            return cell(f"{sw} → {dav}")[:90]
        return cell(f"{e.get('match', '')} ({e['pair_id']})")
    if r.get("verified_examples"):
        v = r["verified_examples"][0]
        return cell(v.get("dav") or v.get("nouns") or v.get("ref"))[:90]
    return ""


def main():
    write(HERE / "RULEBOOK.md", None)
    if TRAIN.exists():
        text = {}
        for line in open(TRAIN, encoding="utf-8"):
            o = json.loads(line)
            text[o["id"]] = (o["swa"], o["dav"])
        write(REVIEW, text)
        print(f"review copy with sentences (not in git): {REVIEW}")


def write(path: Path, text: dict | None):
    d = json.loads((HERE / "rules.json").read_text(encoding="utf-8"))
    rules, meta = d["rules"], d["_meta"]
    out = ["# Kidaw'ida rule book (generated — do not edit)", "",
           f"Generated by `rulebook/render.py` from `rules.json` (built by `{meta['built_by']}`, git "
           f"`{meta['git_sha'][:8]}`). Sections done: {meta['sections_done']}. "
           f"{len(rules)} rules. Corpus evidence = pairs in the clean train split "
           f"({meta['config']['n_train_pairs']:,} pairs) where the Swahili condition and the Kidaw'ida "
           f"form co-occur; lift = how much more often than without the condition. Rules need ≥ "
           f"{meta['config']['min_evidence']} pairs and lift ≥ {meta['config']['min_lift']} unless speaker-verified.",
           "", "Source: speaker = native-speaker verified; corpus = attested in clean train. "
           "⚠ = conflicting readings recorded (default first). Rank 1 = default reading for that condition.", ""]
    for sec, title in SECTIONS.items():
        rs = [r for r in rules if r["section"] == sec]
        if not rs:
            continue
        out += [f"## {sec}. {title}", "", "| id | if | then | source | n | lift | status | example |",
                "|---|---|---|---|---|---|---|---|"]
        for r in rs:
            lift = r["evidence"].get("lift", "")
            flag = " ⚠" if r["conflict"] else ""
            rank = f" (rank {r['rank']})" if "rank" in r else ""
            out.append(f"| `{r['id']}`{flag} | {cell(r['if'])} | {form_text(r)}{rank} | {SRC[r['source']]} | "
                       f"{r['evidence_count']} | {'' if lift is None else lift} | {r['status']} | {example(r, text)} |")
        out.append("")
    conf = [r for r in rules if r["conflict"]]
    out += ["## Conflicts", "", "| id | readings | notes |", "|---|---|---|"]
    for r in conf:
        out.append(f"| `{r['id']}` | {cell(r.get('readings', ''))} | {cell(r.get('notes', ''))} |")
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {path.name}: {len(rules)} rules, {len(conf)} conflicts")


if __name__ == "__main__":
    main()
